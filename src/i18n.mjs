function fromQuery() {
  try {
    const value = new URLSearchParams(globalThis.location?.search || "").get(
      "lang",
    );
    return LOCALES.includes(value) ? value : "";
  } catch {
    return "";
  }
}

export function readLocale() {
  const query = fromQuery();
  if (query) {
    writeLocale(query);
    return query;
  }
  try {
    const saved = globalThis.localStorage?.getItem(STORAGE_KEY);
    if (LOCALES.includes(saved)) return saved;
  } catch {
    /* private mode */
  }
  return DEFAULT_LOCALE;
}

export function applyDocument(locale, title) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
  if (title) document.title = title;
}

export function writeLocale(locale) {
  if (!LOCALES.includes(locale)) return DEFAULT_LOCALE;
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, locale);
  } catch {
    /* private mode */
  }
  return locale;
}

export function t(locale, key, vars = {}) {
  const table = MESSAGES[locale] || MESSAGES.en;
  let text = table[key] ?? MESSAGES.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
